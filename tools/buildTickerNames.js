'use strict';

// Build the company-name -> ticker table the Sevcik extractor needs.
//
// WHY A GENERATED TABLE AND NOT A HARD-CODED ONE
//
// The Sevcik channel is spoken Czech, and the speaker says COMPANY
// NAMES, not ticker symbols. Measured on one real 50-minute stream
// (2026-11-04, UX1IRkmxIUo):
//
//   Apple   17 mentions      TSLA   1
//   Tesla    7 mentions      AAPL   0
//   Meta     5 mentions      AMZN   0
//   Amazon   4 mentions      MSFT   0
//   Microsoft 3 mentions     NVDA   0
//
// The ticker symbols ARE in the seed lexicon -- but they barely appear in
// the text, so a symbol-only extractor finds almost nothing on a real
// stream.
//
// The source is the SEC's own company_tickers.json, which is the
// authoritative list of every US-listed ticker and its registrant name.
// It is free, it needs no key, and it is regenerated by this tool rather
// than typed by hand.
//
// THE MATCHING PROBLEM
//
// The SEC names are LEGAL ENTITY names: "AMAZON COM INC", "NVIDIA CORP",
// "BERKSHIRE HATHAWAY INC". The speaker says "Amazon", "Nvidia",
// "Berkshire". So a literal comparison finds nothing.
//
// The matcher therefore compares on a NORMALIZED form: the legal suffix
// and the legal-form words are stripped, the rest is folded, and the
// spoken form has to match what is left.
//
//   "AMAZON COM INC"      -> "amazon"
//   "NVIDIA CORP"         -> "nvidia"
//   "BERKSHIRE HATHAWAY INC" -> "berkshire hathaway"
//   "APPLE INC"           -> "apple"
//
// And then a spoken name is matched to the ticker whose normalized form
// CONTAINS it, longest first -- so "Berkshire Hathaway" beats
// "Berkshire", and "Amazon" never matches "Amazon.com" by accident.
//
// WHAT IT DOES NOT DO
//
// It does not try to be a company-name database. It records the
// normalized names and the tickers, and the MATCHER (in
// src/sevcik/companyNames.js) decides what a spoken word means. A
// generated table that is regenerated is a table that can be audited and
// diffed; a hand-written one is a list of claims nobody can check.
//
// Usage:
//   node tools/buildTickerNames.js
//   node tools/buildTickerNames.js --source path/to/company_tickers.json
//   node tools/buildTickerNames.js --dry-run
//   node tools/buildTickerNames.js --json

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUT_PATH = path.join(ROOT, 'config', 'ticker_company_names.csv');

// The SEC's file. It is small (about 800 KB) and is fetched with a
// User-Agent because the SEC requires one.
const DEFAULT_SOURCE_URL = 'https://www.sec.gov/files/company_tickers.json';

const argv = process.argv.slice(2);

/**
 * The legal-form words and suffixes that carry no information about what
 * a company is called.
 *
 * These are stripped from the registrant's name before matching, because
 * the speaker never says them: nobody says "Amazon com inc" or
 * "NVIDIA corporation".
 */
const LEGAL_FORMS = [
  'incorporated', 'inc', 'corp', 'corporation',
  'company', 'com', 'co', 'llc', 'l.l.c.', 'lp', 'l.p.', 'ltd', 'ltd.',
  'limited', 'plc', 'p.l.c.', 'sa', 's.a.', 'ag', 'a.g.', 'nv', 'n.v.',
  'se', 's.e.', 'ab', 'a.b.', 'as', 'a.s.', 'oy', 'ohj', 'group',
  'holding', 'holdings', 'trust', 'the', 'and', '&',
];

/**
 * Words that are part of a company's SPOKEN name and must not be
 * stripped.
 *
 * "Meta Platforms" is spoken as "Meta", and "Advanced Micro Devices" is
 * spoken as "AMD" or "Advanced Micro". So the last word of a name is
 * kept even when it is in the legal-forms list -- "Meta Platforms" keeps
 * "platforms", because dropping it would leave "meta" as the only name
 * and "Meta Platforms" would never match "Meta".
 *
 * The rule is therefore: strip the legal forms, but if that would leave
 * nothing, keep the original.
 *
 * @param {string} name
 * @returns {string}
 */
function stripLegalForms(words) {
  const kept = words.filter((word) => !LEGAL_FORMS.includes(word));
  return kept.length ? kept : words;
}

/**
 * Fold a name to the form that is compared.
 *
 * The rules, in order:
 *
 *   1. drop the punctuation
 *   2. drop the legal-form words
 *   3. fold to lower case
 *
 * The result is what a spoken name has to match. "AMAZON COM INC" becomes
 * "amazon", and "Apple Inc." becomes "apple".
 *
 * @param {string} name
 * @returns {string}
 */
function normalizeCompanyName(name) {
  const text = String(name || '').toLowerCase().replace(/[,./]/g, ' ');
  const words = text.split(/\s+/).filter(Boolean);
  return stripLegalForms(words).join(' ').trim();
}

/**
 * Write the table.
 *
 * @param {Array<{ticker: string, name: string, normalized: string}>} rows
 * @param {string} outPath
 * @returns {void}
 */
function writeTable(rows, outPath) {
  const lines = [
    '# Company names, for matching a SPOKEN company name to a ticker.',
    '#',
    '# GENERATED by tools/buildTickerNames.js from the SEC company_tickers.json.',
    '# Do not edit by hand -- regenerate it instead.',
    '#',
    '# The source names are legal entity names ("AMAZON COM INC"). The',
    '# normalized column is what the matcher compares against, with the',
    '# legal-form words removed ("amazon").',
    '#',
    '# source: https://www.sec.gov/files/company_tickers.json',
    'ticker,name,normalized',
  ];

  for (const row of rows) {
    const name = row.name.includes(',') ? `"${row.name.replace(/"/g, '""')}"` : row.name;
    lines.push(`${row.ticker},${name},${row.normalized.replace(/,/g, ' ')}`);
  }

  fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');
}

async function main() {
  const dryRun = argv.includes('--dry-run');
  const json = argv.includes('--json');
  const sourceArg = readFlag(argv, '--source');

  let payload;
  if (sourceArg) {
    payload = JSON.parse(fs.readFileSync(sourceArg, 'utf8'));
  } else {
    const response = await fetch(DEFAULT_SOURCE_URL, {
      headers: {
        // The SEC requires a User-Agent that identifies the caller.
        'User-Agent': 'portfolio_analyzer_revere (ticker name table generator)',
        'Accept-Encoding': 'gzip, deflate',
      },
    });
    if (!response.ok) {
      console.error(`[ticker-names] SEC returned HTTP ${response.status}`);
      process.exit(1);
    }
    payload = await response.json();
  }

  const records = Object.values(payload);
  const rows = [];
  const seen = new Set();

  for (const record of records) {
    const ticker = String(record.ticker || '').trim().toUpperCase();
    const name = String(record.title || '').trim();
    if (!ticker || !name) continue;
    if (seen.has(ticker)) continue;
    seen.add(ticker);

    const normalized = normalizeCompanyName(name);
    if (!normalized) continue;

    rows.push({ ticker, name, normalized });
  }

  rows.sort((a, b) => a.ticker.localeCompare(b.ticker));

  if (!dryRun) writeTable(rows, OUT_PATH);

  console.log(`[ticker-names] ${records.length} SEC records -> ${rows.length} rows`
    + ` (${dryRun ? 'dry-run' : path.relative(ROOT, OUT_PATH)})`);

  if (json) {
    console.log(JSON.stringify({ source: sourceArg || DEFAULT_SOURCE_URL, rows: rows.length }, null, 2));
  }
}

/**
 * Read a flag's value.
 *
 * @param {string[]} args
 * @param {string} name
 * @returns {string}
 */
function readFlag(args, name) {
  const index = args.indexOf(name);
  if (index === -1) return '';
  return String(args[index + 1] || '');
}

if (require.main === module) {
  main().catch((error) => {
    console.error(`[ticker-names] failed: ${error && error.message ? error.message : error}`);
    process.exit(1);
  });
}

module.exports = { LEGAL_FORMS, normalizeCompanyName };
