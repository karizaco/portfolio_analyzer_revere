'use strict';

const fs = require('node:fs');
const path = require('node:path');

// Portable paths for COMMITTED artifacts.
//
// THE PROBLEM THIS SOLVES
// A probe log records the absolute paths of the files it touched:
//
//   "video_path": "C:\\Users\\admin\\Projects\\portfolio_analyzer_revere\\data\\video_pipeline\\downloads_hires\\20260603_gzKJIHyBPfA.mp4"
//   "output_path": "C:\\Users\\admin\\Projects\\portfolio_analyzer_revere\\data\\video_scan_20260915\\...\\screenshots\\20260603_ps.png"
//
// The logs are committed, and `data/analysis.json` is committed, so those
// strings end up naming one person's home directory inside a tracked file.
// On any other machine the path resolves to nothing, and the artifact
// cannot be regenerated byte-identically from a fresh clone — the aggregator
// would have to be run on the original machine to reproduce it.
//
// The repository already has a rule for this, in `src/video/downloadCandidates.js`
// and `tools/whiteboard_worker.py`: a path inside the repository is stored
// relative to the repository root; a path outside keeps its absolute form.
//
// THE EXTRA CASE
// That rule works for a path the CURRENT machine wrote, because the current
// machine knows its own repository root. The paths in a probe log were
// written by whichever machine ran the scan — often a different one — so
// "is this inside the repository?" cannot be answered by comparing against
// the current root.
//
// The answer comes from the repository's own layout instead: everything
// inside the repository lives under `data/`, so a recorded path that
// contains that segment is inside a checkout of this repository, wherever
// that checkout was. What follows the segment has to be a directory this
// repository actually has, so that an unrelated path that happens to
// contain a `data` directory (`D:\\my\\data\\videos\\x.mp4`) is left alone
// rather than silently truncated to a path that does not exist.

// The repository's data directory. Every in-repo path starts here.
const REPO_DATA_DIR = 'data';

// A key whose value names a path. Only values under such a key are
// rewritten, so OCR text that happens to contain something path-shaped is
// left exactly as the OCR engine returned it.
const PATH_KEY = /(?:^|_)(?:path|dir|directory|root)$/;

/**
 * Is this string an absolute path, on any platform?
 *
 * Windows drives (`C:\`), UNC shares (`\\server\share`), POSIX roots (`/x`)
 * and Windows' own root-relative form (`\x`) all count. The check is done
 * on the string rather than through `path.isAbsolute`, because a POSIX
 * process reading a path that a Windows machine wrote has to recognise it
 * as absolute too.
 *
 * @param {unknown} value
 * @returns {boolean}
 */
function isAbsolutePath(value) {
  if (typeof value !== 'string' || value === '') return false;
  if (/^[A-Za-z]:[\\/]/.test(value)) return true;
  if (value.startsWith('/')) return true;
  if (value.startsWith('\\\\')) return true;
  return path.isAbsolute(value);
}

/**
 * Does this key name a path?
 *
 * @param {string} key
 * @returns {boolean}
 */
function isPathKey(key) {
  return PATH_KEY.test(String(key));
}

/**
 * The path relative to `root`, or null when it is not under it.
 *
 * Done with string comparison rather than `path.relative`, because
 * `path.relative` resolves both arguments against the current working
 * directory — which turns a foreign drive letter into a nonsense relative
 * path on a POSIX machine.
 *
 * @param {string} root
 * @param {string} target
 * @returns {string|null}
 */
function relativeUnder(root, target) {
  const normalisedRoot = String(root).replace(/\\/g, '/').replace(/\/+$/, '');
  const normalisedTarget = String(target).replace(/\\/g, '/');
  if (normalisedRoot === '') return null;
  if (!normalisedTarget.toLowerCase().startsWith(`${normalisedRoot.toLowerCase()}/`)) return null;
  return normalisedTarget.slice(normalisedRoot.length + 1);
}

/**
 * Is this the name of a directory the repository has under `data/`?
 *
 * @param {string} name
 * @param {string|null} repoRoot
 * @returns {boolean}
 */
function isRepoDataDir(name, repoRoot) {
  if (!name || name === '.' || name === '..') return false;
  // A scan directory is named after its date, so one written by another
  // machine may not exist in this checkout. Its name is still unambiguous.
  if (/^video_scan_\d{8}$/.test(name)) return true;
  if (!repoRoot) return false;
  try {
    return fs.existsSync(path.join(repoRoot, REPO_DATA_DIR, name));
  } catch {
    return false;
  }
}

/**
 * The path relative to the repository root, for a path recorded on another
 * machine, or null when this path is not inside the repository.
 *
 * @param {string} target
 * @param {string|null} repoRoot
 * @returns {string|null}
 */
function relativeToRepoData(target, repoRoot) {
  const normalised = String(target).replace(/\\/g, '/');
  const needle = `/${REPO_DATA_DIR}/`;
  // The LAST occurrence: a path may contain `data` higher up — a home
  // directory called `data`, say — and the repository's own data directory
  // is the deepest one.
  const index = normalised.lastIndexOf(needle);
  if (index === -1) return null;
  const relative = normalised.slice(index + 1);
  const first = relative.split('/')[1];
  if (!isRepoDataDir(first, repoRoot)) return null;
  return relative;
}

/**
 * Turn a recorded path into one that still means something on another
 * machine.
 *
 * A path inside the repository becomes relative to the repository root; a
 * path outside it keeps its absolute form, because there is no honest
 * relative form for a file that lives somewhere else entirely.
 *
 * @param {unknown} value
 * @param {object} [options]
 * @param {string|null} [options.repoRoot] - the repository root, used to
 *   recognise a path under this checkout and to check that a `data`
 *   directory really exists.
 * @returns {unknown}
 */
function toPortableArtifactPath(value, options = {}) {
  if (typeof value !== 'string' || value === '') return value;
  if (!isAbsolutePath(value)) {
    // Already relative: portable as it stands. Normalising the separators
    // keeps the artifact identical whichever machine wrote it.
    return value.replace(/\\/g, '/');
  }

  const repoRoot = options.repoRoot || null;

  // 1. Under this checkout.
  const under = repoRoot ? relativeUnder(repoRoot, value) : null;
  if (under) return under;

  // 2. Under a checkout of this repository somewhere else — the usual case
  //    for a probe log that was committed from another machine.
  const inRepoData = relativeToRepoData(value, repoRoot);
  if (inRepoData) return inRepoData;

  // 3. Outside the repository: no honest relative form exists.
  return value;
}

/**
 * Rewrite every path a tree holds, in place.
 *
 * Only values under a key that names a path are touched, so OCR text is
 * never rewritten.
 *
 * @param {unknown} node
 * @param {object} [options] - passed to {@link toPortableArtifactPath}
 * @returns {unknown} the same tree
 */
function portabilizePaths(node, options = {}) {
  if (Array.isArray(node)) {
    for (const item of node) portabilizePaths(item, options);
    return node;
  }
  if (!node || typeof node !== 'object') return node;
  for (const [key, value] of Object.entries(node)) {
    if (typeof value === 'string') {
      if (isPathKey(key)) node[key] = toPortableArtifactPath(value, options);
      continue;
    }
    portabilizePaths(value, options);
  }
  return node;
}

/**
 * Every string value in a tree that holds an absolute path.
 *
 * Used to check a committed artifact: an absolute path is only acceptable
 * when it points OUTSIDE the repository.
 *
 * @param {unknown} node
 * @param {object} [options]
 * @param {string} [options.keyPrefix]
 * @returns {Array<{keyPath: string, value: string}>}
 */
function findAbsolutePathValues(node, options = {}) {
  const prefix = options.keyPrefix || '';
  const found = [];
  (function walk(value, keyPath) {
    if (typeof value === 'string') {
      if (isAbsolutePath(value)) found.push({ keyPath, value });
      return;
    }
    if (Array.isArray(value)) {
      value.forEach((item, index) => walk(item, `${keyPath}[${index}]`));
      return;
    }
    if (value && typeof value === 'object') {
      for (const [key, item] of Object.entries(value)) {
        walk(item, keyPath ? `${keyPath}.${key}` : key);
      }
    }
  }(node, prefix));
  return found;
}

module.exports = {
  REPO_DATA_DIR,
  findAbsolutePathValues,
  isAbsolutePath,
  isPathKey,
  portabilizePaths,
  relativeToRepoData,
  relativeUnder,
  toPortableArtifactPath
};
