'use strict';

// Match a SPOKEN company name to a ticker.
//
// WHY THIS EXISTS
//
// The Sevcik channel is spoken Czech, and the speaker says COMPANY
// NAMES, not ticker symbols. Measured on one real 50-minute stream
// (2026-11-04, UX1IRkmxIUo):
//
//   Apple    17 mentions      TSLA   1
//   Tesla     7 mentions      AAPL   0
//   Meta      5 mentions      AMZN   0
//   Amazon    4 mentions      MSFT   0
//   Microsoft 3 mentions      NVDA   0
//
// The ticker symbols ARE in the seed lexicon -- but they barely appear in
// the text, so a symbol-only extractor finds almost nothing on a real
// stream.
//
// THE SOURCE
//
// `config/ticker_company_names.csv`, generated by
// `tools/buildTickerNames.js` from the SEC's own company_tickers.json.
// The SEC is the authoritative list of US-listed tickers and their
// registrant names, it is free, and it needs no key.
//
// The names it carries are LEGAL ENTITY names -- "AMAZON COM INC",
// "NVIDIA CORP" -- and the speaker says "Amazon" and "Nvidia". So the
// table carries a NORMALIZED column as well, with the legal-form words
// removed, and the matcher compares against that.
//
// THE MATCHING
//
// A spoken word is matched to a ticker when the ticker's normalized name
// CONTAINS the spoken word, and the LONGEST such name wins. So:
//
//   "berkshire hathaway"  beats "berkshire"
//   "amazon"              matches AMZN, not "Amazon.com"
//   "meta platforms"      matches META
//
// The containment is the other way round from what it looks like: the
// SPOKEN name is the needle and the normalized company name is the
// haystack. A company whose full name is longer than what was said
// still matches, because the speaker said part of it.
//
// THE CZECH INFLECTION
//
// Czech inflects the case ending: "Apple" is "Applu", "Tesla" is "Tesly",
// "Nvidia" is "Nvidii". The matcher therefore compares on a stem: the
// trailing vowels of the last word are dropped, so "Applu" and "Apple"
// share the stem "apl".
//
// THE AMBIGUITY RULE
//
// A spoken name that matches MORE THAN ONE ticker is not a ticker. "Meta"
// could be META, and if the table also had a "Metabolix" it would match
// that too. So an ambiguous match is dropped rather than guessed -- the
// same rule the OCR path uses for a correction at the same edit
// distance, and for the same reason: a wrong holding in a portfolio
// report is worse than a missing one.
//
// THE TICKER AS A NAME
//
// A spoken word that is ALREADY a ticker symbol is also a company name:
// "SPY" is said as "spy", "AMD" as "AMD". The ticker symbols themselves
// are therefore searched too, so a symbol that is said out loud is
// found.
//
// THE NON-US PROBLEM
//
// The speaker trades and names non-US stocks -- he said "RHM, neboli
// Rheinmetall" (a German company, priced in euros). The SEC file covers
// US listings only, so a non-US ticker is NOT in the table and its
// COMPANY NAME will not match.
//
// So a spoken name that matches nothing in the table, and that is not a
// known ticker either, is reported as an UNKNOWN NAME rather than
// silently dropped. That is what lets the table grow from measurement
// instead of from assumption.

