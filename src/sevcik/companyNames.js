/**
 * Does the haystack contain the needle, on a WORD BOUNDARY?
 *
 * The needle's words must appear in the haystack, in order, and the
 * first of them must start a word.
 *
 * This is what stops "Apple" from matching "applied materials":
 * "appl" is inside "applied", but it does not start a word there.
 *
 * @param {string} haystack
 * @param {string} needle
 * @returns {boolean}
 */
function containsWords(haystack, needle) {
  const hay = String(haystack || '').split(/\s+/).filter(Boolean);
  const pin = String(needle || '').split(/\s+/).filter(Boolean);
  if (!hay.length || !pin.length) return false;

  for (let start = 0; start <= hay.length - pin.length; start += 1) {
    let matched = true;
    for (let offset = 0; offset < pin.length; offset += 1) {
      if (hay[start + offset] !== pin[offset]) {
        matched = false;
        break;
      }
    }
    if (matched) return true;
  }
  return false;
}

/**
 * Find the ticker a spoken company name refers to.
 *
 * @param {string} spoken - the word as it was said
 * @param {object} [options]
 * @param {string} [options.tablePath]
 * @param {Set<string>} [options.lexicon] - the tickers that may be reported
 * @returns {{ticker: string|null, matched: string, ambiguous: string[]}}
 */
function matchCompanyName(spoken, options = {}) {
  const raw = String(spoken || '').trim();
  const result = { ticker: null, matched: '', ambiguous: [], shareClasses: [], viaAlias: false };

  if (!raw || raw.length < MIN_NAME_LENGTH) return result;

  const stem = stemName(raw);
  if (!stem || stem.length < MIN_NAME_LENGTH) return result;
  if (STOP_WORDS.has(stem)) return result;

  const table = loadCompanyNames(options);
  const lexicon = options.lexicon;

  // The SPOKEN-NAME ALIASES are checked FIRST, because they are the
  // measured cases: a name the speaker actually used that the SEC's
  // registrant names cannot reach. "Alphabet" is the registrant and
  // "Google" is what is said, and only the alias table knows that.
  const aliasKey = stem;
  const aliasTicker = SPOKEN_NAME_ALIASES[aliasKey]
    || SPOKEN_NAME_ALIASES[raw.toLowerCase()]
    || SPOKEN_NAME_ALIASES[raw.toLowerCase().trim()];
  if (aliasTicker) {
    if (!lexicon || lexicon.has(aliasTicker)) {
      result.ticker = aliasTicker;
      result.matched = raw.toLowerCase();
      result.viaAlias = true;
      return result;
    }
  }

  const matches = [];

  for (const row of table) {
    // The ticker has to be one the caller is allowed to report.
    if (lexicon && !lexicon.has(row.ticker)) continue;

    const nameStem = stemName(row.normalized);
    if (!nameStem) continue;

    // The spoken name is the needle, the company name is the haystack:
    // "Amazon" matches "amazon", and "Berkshire" matches "berkshire
    // hathaway".
    //
    // The containment is on a WORD BOUNDARY, not on raw characters. A
    // raw substring match gave "Apple" -> AMAT ("applied materials de"),
    // because "apple" is inside "appl". A word-boundary match requires
    // the spoken words to be a whole run of the company's words, in
    // order, and to start at a word boundary.
    if (!containsWords(nameStem, stem)) continue;

    matches.push(row);
  }

  if (!matches.length) return result;

  // The LONGEST matching name wins: "berkshire hathaway" over
  // "berkshire".
  matches.sort((a, b) => b.normalized.length - a.normalized.length);

  const best = matches[0];
  const tied = matches.filter((row) => row.normalized.length === best.normalized.length);

  if (tied.length > 1) {
    // Two companies share the name. That is not a ticker -- it is a
    // guess, and a wrong holding is worse than a missing one.
    //
    // EXCEPT when they are SHARE CLASSES of one company: GOOG and GOOGL
    // are both Alphabet, and a speaker who says "Alphabet" means the
    // company, not one of its two share classes. The canonical ticker is
    // the one the file lists first -- which is the class A share, the one
    // that is quoted by default and the one every price feed leads with.
    const distinctCompanies = new Set(tied.map((row) => row.normalized));
    if (distinctCompanies.size === 1) {
      result.ticker = tied[0].ticker;
      result.matched = best.normalized;
      result.shareClasses = tied.map((row) => row.ticker).sort();
      return result;
    }

    result.ambiguous = tied.map((row) => row.ticker).sort();
    result.matched = best.normalized;
    return result;
  }

  result.ticker = best.ticker;
  result.matched = best.normalized;
  return result;
}

